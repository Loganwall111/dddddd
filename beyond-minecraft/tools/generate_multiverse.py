def png(width, height, rgba):
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    rows = b"".join(b"\0" + bytes(rgba[y * width * 4:(y + 1) * width * 4]) for y in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def _mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def _shift(color, turn):
    """Deterministic palette rotation for echo realms beyond the twelve named worlds."""
    if turn <= 0:
        return color
    rotate = turn % 3
    shifted = tuple(color[(i + rotate) % 3] for i in range(3))
    factor = 1.0 - .10 * ((turn % 4) + 1)
    return tuple(max(6, min(250, int(v * factor))) for v in shifted)


def block_texture(seed, base, glow, kind, pattern):
    """16x16 material. Every realm gets its own pattern family, not just a recolour."""
    rng = random.Random(seed ^ (zlib.crc32(kind.encode()) & 0xFFFF))
    frames = 4 if kind == "crystal" else 1
    noise = [rng.uniform(-1, 1) for _ in range(256)]
    pixels = []
    for frame in range(frames):
        for y in range(16):
            for x in range(16):
                g = noise[(y * 16 + x + frame * 7) & 255]
                vein = abs(math.sin(x * .42 + math.sin(y * .68) * 1.6)) < .20
                bevel = .80 if x in (0, 15) or y in (0, 15) else 1.0
                if kind == "crystal":
                    pulse = .62 + .20 * math.sin(frame * math.pi / 2 + (x + y) * .28)
                    color = [c * (pulse if vein else .25 + g * .06) * bevel for c in glow]
                elif kind == "flora":
                    dense = 1.0 if rng.random() < .18 else 0.0
                    color = [(base[i] * .55 + glow[i] * .45) * (.72 + g * .20 + dense * .20) for i in range(3)]
                elif kind == "core":
                    color = [base[i] * .38 * (1 + g * .30) + (glow[i] * .07 if pattern == "facet" else 0) for i in range(3)]
                elif kind == "surface":
                    color = [c * (.72 + g * .22) for c in _mix(base, glow, .30)]
                else:  # stratum, and any realm-specific substitute
                    color = [base[i] * (1 + g * .25) + (glow[i] * .20 if vein else 0) for i in range(3)]

                # Pattern overlays. These are the realm's "material identity".
                t = (x + y) / 30.0
                if pattern == "strata":
                    shade = .78 + .22 * math.sin(y * 1.15 + g * .4)
                    color = [c * shade for c in color]
                elif pattern == "crack":
                    crack = min(abs(math.sin(x * .8 + g * 2.0)), abs(math.cos(y * .7 - g * 1.4)))
                    if crack < .10:
                        color = [c * .35 for c in color]
                elif pattern == "scale":
                    cell = ((x // 4) + (y // 4)) % 2
                    color = [c * (.86 + .14 * cell) for c in color]
                elif pattern == "grid":
                    if x % 8 == 0 or y % 8 == 0:
                        color = [c * .28 for c in color]
                    elif x % 8 in (1, 7) or y % 8 in (1, 7):
                        color = [c * 1.22 for c in color]
                elif pattern == "facet":
                    color = [c * (.70 + .30 * abs(math.sin(x * .9) * math.cos(y * .9))) for c in color]
                elif pattern == "wave":
                    color = [c * (.80 + .24 * math.sin((x * .6 + y * .25))) for c in color]
                elif pattern == "fibre":
                    color = [c * (.86 + .18 * math.sin(y * 2.1 + x * .3)) for c in color]
                elif pattern == "sponge":
                    if (x % 8 in (2, 5)) and (y % 8 in (2, 5)):
                        color = [c * .30 for c in color]
                elif pattern == "bubble":
                    r = math.hypot(x - 7.5, y - 7.5)
                    color = [c * (.65 + .75 * math.exp(-((r - 5.0) ** 2) * 1.4)) for c in color]
                elif pattern == "grain":
                    color = [c * (1.0 + .06 * math.sin(t * 12.0)) for c in color]
                pixels.extend([min(255, max(0, round(c))) for c in color] + [255])
    return png(16, 16 * frames, pixels)


def icon(kind, size=32):
    pixels = []
    for y in range(size):
        for x in range(size):
            u, v = (x + .5) / size * 2 - 1, (y + .5) / size * 2 - 1
            r = math.hypot(u, v)
            color = (0, 0, 0, 0)
            if kind == "reality_knife":
                blade = abs(u + v + .22) < .19 and -.77 < v < .19
                handle = abs(u + v + .2) < .23 and .15 < v < .73
                if blade: color = (166, 247, 248, 255) if u + v < -.22 else (111, 63, 204, 255)
                if handle: color = (52, 37, 77, 255)
                if abs(v - .19) < .08 and abs(u) < .4: color = (226, 181, 101, 255)
            elif kind == "radiate_reality_glasses":
                lens = abs(abs(u) - .37) < .28 and abs(v) < .28
                frame = abs(abs(u) - .37) < .34 and abs(v) < .36
                bridge = abs(u) < .15 and abs(v) < .08
                if frame or bridge: color = (213, 179, 104, 255)
                if lens: color = (69 + int(70 * (1 - abs(v))), 177, 205, 230)
            elif kind == "field_guide":
                if abs(u) < .61 and abs(v) < .79: color = (22, 42, 51, 255)
                if -.59 < u < -.46 and abs(v) < .79: color = (181, 142, 78, 255)
                if .15 < abs(v) < .20 and abs(u) < .30: color = (113, 219, 217, 255)
                if abs(math.hypot(u - .07, v) - .30) < .055: color = (228, 193, 126, 255)
                if math.hypot(u - .07, v) < .09: color = (211, 251, 238, 255)
            elif kind == "reality_tear":
                # A ragged vertical cut with a bright edge: the tool that rips the membrane open.
                cut = abs(u + .18 * math.sin(v * 7.0)) < .16
                if cut and abs(v) < .88: color = (18, 16, 30, 255)
                edge = abs(abs(u + .18 * math.sin(v * 7.0)) - .16) < .05 and abs(v) < .88
                if edge: color = (196, 140, 255, 255)
                if cut and r < .55: color = (86, 232, 226, 255)
                if abs(u) < .05 and abs(v) > .80: color = (226, 181, 101, 255)
            else:
                shape = abs(u) * .8 + abs(v) < .77
                cut = abs(u + .15 * math.sin(v * 8)) < .085
                if shape:
                    color = (180, 138, 245, 255) if u < 0 else (73, 222, 225, 255)
                    if kind == "shattered_relic" and cut: color = (19, 17, 33, 255)
                    if abs(v) < .05 or abs(u) < .05: color = (235, 234, 255, 255)
            pixels.extend(color)
    return png(size, size, pixels)


def critter_texture(seed, base, glow):
    """Deliberately mottled so any face mapping reads as hide: safe for the code-built quadruped.

    The model's eye cubes sample the painted glow patch at (56,56); the spine strip at x=62 gives
    the back a readable ridge. Everything else is noise, which is what makes blind UV mapping safe.
    """
    rng = random.Random(seed ^ 0x5EED)
    size = 64
    pixels = []
    for y in range(size):
        for x in range(size):
            g = rng.uniform(-1, 1) * .5 + rng.uniform(-1, 1) * .3
            belly = max(0.0, 1.0 - abs(y - 46) / 12.0) * .5
            spot = 1.0 if rng.random() < .04 else 0.0
            c = _mix(base, glow, .18 + belly * .55 + spot * .5)
            c = [v * (1 + g * .28) for v in c]
            pixels.extend([min(255, max(0, round(v))) for v in c] + [255])
    def put(x, y, color):
        pixels[(y * size + x) * 4:(y * size + x + 1) * 4] = list(min(255, max(0, c)) for c in color) + [255]
    for x in range(56, 64):
        for y in range(56, 64):
            put(x, y, (min(255, glow[0] + 70), min(255, glow[1] + 70), min(255, glow[2] + 70)))
    for y in range(2, 50):
        put(62, y, tuple(int(v * 1.25) for v in glow))
    return png(size, size, pixels)


def density(kind, **args):
    return {"type": "minecraft:" + kind, **args}


def terrain_router(recipe, key, theme, rng):
    """One genuinely different terrain equation per realm family."""
    surface = density("y_clamped_gradient", from_y=-40 + theme * 3, to_y=216 - theme * 2, from_value=-1.5, to_value=1.5)
    primary = density("noise", noise=f"beyond:{key}_terrain", xz_scale=.65 + theme * .065, y_scale=1.15 + theme * .06)
    secondary = density("noise", noise=f"beyond:{key}_detail", xz_scale=1.7 + theme * .11, y_scale=.55)
    if recipe == "canopy":
        shelves = density("mul", argument1=secondary, argument2=density("abs", argument=density("add",
            argument1=-16.0, argument2=density("mul", argument1=8.0, argument2=secondary))))
        body = density("add", argument1=density("mul", argument1=1.4, argument2=primary), argument2=shelves)
        final = density("add", argument1=body, argument2=density("mul", argument1=-1.0, argument2=density("abs", argument=surface)))
    elif recipe == "spire":
        ridges = density("mul", argument1=secondary, argument2=density("abs", argument=secondary))
        final = density("add", argument1=density("mul", argument1=2.2, argument2=density("add",
            argument1=density("mul", argument1=.9, argument2=primary), argument2=ridges)),
            argument2=density("mul", argument1=-1.15, argument2=density("abs", argument=surface)))
    elif recipe == "canyon":
        plateaus = density("clamp", input=density("mul", argument1=3.0, argument2=surface), min=-1.0, max=1.0)
        final = density("add", argument1=density("mul", argument1=.55, argument2=primary),
            argument2=density("mul", argument1=-1.0, argument2=density("abs", argument=plateaus)))
    elif recipe == "plateau":
        stepped = density("clamp", input=density("mul", argument1=2.0, argument2=surface), min=-1.0, max=1.0)
        # The gradient increases with Y: invert it so this plateau solidifies below its crown
        # and reliably leaves open sky above, rather than filling the realm to the build limit.
        quantized = density("mul", argument1=-.5, argument2=density("add", argument1=stepped, argument2=density("squeeze", argument=stepped)))
        final = density("add", argument1=density("mul", argument1=.9, argument2=primary), argument2=quantized)
    elif recipe == "bloom":
        bulbs = density("mul", argument1=primary, argument2=density("mul", argument1=secondary, argument2=2.2))
        final = density("add", argument1=density("mul", argument1=1.8, argument2=bulbs),
            argument2=density("mul", argument1=-1.0, argument2=density("abs", argument=surface)))
    elif recipe == "ocean":
        seabed = density("add", argument1=.25, argument2=density("mul", argument1=.45, argument2=primary))
        islands = density("mul", argument1=secondary, argument2=density("abs", argument=density("add",
            argument1=-30.0, argument2=density("mul", argument1=12.0, argument2=primary))))
        final = density("add", argument1=seabed, argument2=islands)
    elif recipe == "cavern":
        solid = density("add", argument1=-.35, argument2=density("mul", argument1=1.1, argument2=primary))
        hollow = density("mul", argument1=-2.2, argument2=density("abs", argument=density("add",
            argument1=-6.0, argument2=density("mul", argument1=10.0, argument2=secondary))))
        final = density("add", argument1=solid, argument2=hollow)
    elif recipe == "dune":
        ripples = density("mul", argument1=.6, argument2=density("squeeze", argument=secondary))
        final = density("add", argument1=density("add", argument1=.15, argument2=density("mul", argument1=.5, argument2=primary)),
            argument2=density("mul", argument1=-1.0, argument2=density("abs", argument=density("add",
                argument1=ripples, argument2=density("mul", argument1=.6, argument2=surface)))))
    else:  # temporal and any fallback share the original gentle recipe
        final = density("add", argument1=density("mul", argument1=1.4, argument2=primary),
            argument2=density("add", argument1=-.06, argument2=density("mul", argument1=-1.0, argument2=density("abs", argument=surface))))
    amplitude = [1.0, round(rng.uniform(.6, 1.2), 4), .45, .18]
    detail_amplitude = [1.0, round(rng.uniform(.4, .9), 4), .3]
    return final, amplitude, detail_amplitude


