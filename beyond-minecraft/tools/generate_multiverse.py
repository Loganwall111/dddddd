def generate(seed=DEFAULT_SEED, count=DEFAULT_REALMS):
    if not 1 <= count <= 32:
        raise ValueError("Realm count must be 1..32; live registry growth is deliberately forbidden")
    rng = random.Random(seed)
    files = {}
    def put(path, value):
        files[path] = value if isinstance(value, bytes) else (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode()
    lang = {
        "itemGroup.beyond": "Beyond Minecraft",
        "tag.item.beyond.realm_crystals": "Realm Crystals",
        "key.category.beyond": "Beyond Minecraft",
        "key.beyond.guide": "Open the Field Guide",
        "key.beyond.mandela": "Cycle reality (glasses)",
        "key.beyond.panic": "Toggle all Beyond visual effects",
        "key.beyond.scale": "Grow / shrink",
        "key.beyond.tear": "Tear the fabric",
        "item.beyond.reality_knife": "Reality Knife",
        "item.beyond.shattered_relic": "Shattered Relic",
        "item.beyond.reality_tear": "Reality Tear",
        "item.beyond.radiate_reality_glasses": "Radiate Reality Glasses",
        "item.beyond.field_guide": "The Beyond Field Guide",
        "item.beyond.scale_prism": "Scale Prism",
        "entity.beyond.realm_critter": "Realm Critter",
        "key.beyond.hud": "Toggle Beyond diagnostics",
    }
    catalog = {"schema": 2, "seed": seed, "realms": []}
    dirt, pickaxe, crystals, soft = [], [], [], []
    template = json.loads((ROOT / "tools/templates/end-1.21.1.json").read_text())
    for i in range(count):
        source = REALMS[i % len(REALMS)]
        realm = source if i < len(REALMS) else dict(source, name=source["name"] + f" / Echo {i // len(REALMS) + 1}",
            base=_shift(source["base"], i // len(REALMS)), glow=_shift(source["glow"], (i // len(REALMS)) * 2))
        key = f"realm_{i:02}"
        theme = i % len(REALMS)
        name, base, glow = realm["name"], realm["base"], realm["glow"]
        realm_seed = rng.randrange(1, 1 << 23)  # exactly representable in a float shader uniform
        blocks = [f"{key}_{kind}" for kind in KINDS]
        custom = realm["terrain"] in ("between", "labyrinth", "fractal")
        catalog["realms"].append({"id": key, "name": name, "theme": theme, "color": realm["fog"],
                                  "seed": realm_seed, "blocks": blocks, "terrain": realm["terrain"],
                                  "ambient": realm["ambient"], "time": realm["time"],
                                  "materials": len(KINDS), "generator": "beyond:" + realm["terrain"] if custom else "minecraft:noise"})
        for kind, block in zip(KINDS, blocks):
            put(f"assets/beyond/textures/block/{block}.png", block_texture(realm_seed, base, glow, kind, realm["pattern"]))
            if kind == "crystal":
                put(f"assets/beyond/textures/block/{block}.png.mcmeta", {"animation": {"frametime": 8, "interpolate": True}})
            put(f"assets/beyond/blockstates/{block}.json", {"variants": {"": {"model": f"beyond:block/{block}"}}})
            put(f"assets/beyond/models/block/{block}.json", {"parent": "minecraft:block/cube_all", "textures": {"all": f"beyond:block/{block}"}})
            put(f"assets/beyond/models/item/{block}.json", {"parent": f"beyond:block/{block}"})
            put(f"data/beyond/loot_table/blocks/{block}.json", {
                "type": "minecraft:block", "pools": [{"rolls": 1, "entries": [{"type": "minecraft:item", "name": f"beyond:{block}"}],
                "conditions": [{"condition": "minecraft:survives_explosion"}]}]})
            lang[f"block.beyond.{block}"] = f"{name} {kind.title()}"
            pickaxe.append(f"beyond:{block}")
            if kind == "flora":
                soft.append(f"beyond:{block}")
        dirt.append(f"beyond:{blocks[1]}")
        crystals.append(f"beyond:{blocks[2]}")
        echo = f"{key}_echo"
        lang[f"item.beyond.{echo}"] = name + " Echo"
        put(f"assets/beyond/textures/item/{echo}.png", block_texture(realm_seed ^ 9741, base, glow, "surface", realm["pattern"]))
        put(f"assets/beyond/models/item/{echo}.json", {"parent": "minecraft:item/generated", "textures": {"layer0": f"beyond:item/{echo}"}})
        put(f"data/beyond/recipe/{echo}.json", {"type": "minecraft:crafting_shapeless", "ingredients": [{"item": f"beyond:{blocks[2]}"}],
            "result": {"id": f"beyond:{echo}", "count": 4}})
        put(f"data/beyond/recipe/{key}_crystal.json", {"type": "minecraft:crafting_shaped", "pattern": ["EE", "EE"],
            "key": {"E": {"item": f"beyond:{echo}"}}, "result": {"id": f"beyond:{blocks[2]}"}})
        placed = decoration({}, realm, key, blocks, theme)
        features = [[] for _ in range(11)]
        placed_links = []
        slot = 4
        for feature_key, definition in placed.items():
            configured, placement = definition["configured"], definition["placement"]
            put(f"data/beyond/worldgen/configured_feature/{feature_key}.json", {"type": configured[0], "config": configured[1]})
